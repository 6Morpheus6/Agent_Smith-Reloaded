test('activity timeline renders web_search results (not a KV dump)', () => {
    if (!JSDOM) return;
    const dom = new JSDOM('<!doctype html><body><div id="tl"></div></body>');
    global.window = dom.window; global.document = dom.window.document;

    delete require.cache[require.resolve('../src/renderer/timeline/eventAdapter.js')];
    delete require.cache[require.resolve('../src/renderer/timeline/activityTimeline.js')];
    require('../src/renderer/timeline/eventAdapter.js'); // attaches window.XKEventAdapter
    const timeline = require('../src/renderer/timeline/activityTimeline.js');

    const container = dom.window.document.getElementById('tl');
    timeline.mount(container, {});
    timeline.handleCodeEvent({ type: 'tool_start', name: 'web_search', args: { query: 'electron-builder' }, callId: 'c1' });
    timeline.handleCodeEvent({
        type: 'tool_result', name: 'web_search', ok: true, callId: 'c1', durationMs: 900,
        result: {
            results: [{ title: 'appimage | electron-builder', url: 'https://www.electron.build/docs/appimage/', snippet: 'AppImage is a self-contained…' }],
            summary: '1. appimage | electron-builder — AppImage is a self-contained…\n   URL: https://www.electron.build/docs/appimage/'
        }
    });

    const html = container.innerHTML;
    assert.ok(html.includes('AppImage is a self-contained'), 'retrieved content must be visible in the timeline');
    assert.ok(html.includes('1 source retrieved'), 'row summary counts sources');
});

