#!/usr/bin/env bash
# build-updatable-appimage.sh — Agent Smith Reloaded v56+
#
# Builds the UPDATABLE Linux AppImage (zsync) from electron-builder's output.
#
# Why this script exists:
#   electron-builder 26.x does NOT embed an AppImage update channel (it only
#   emits an electron-updater .blockmap, which this app doesn't use). The
#   classic "AppImage updates" mechanism is the UPDATEINFO header string that
#   raw `appimagetool -u` writes into the image. So:
#     1) npm run dist            -> release/linux-unpacked/ + .deb (+ a plain AppImage we discard)
#     2) this script             -> assembles an AppDir from linux-unpacked +
#                                   vendor/appdir-chrome (AppRun/.desktop/icons/usr libs),
#                                   then runs appimagetool -u with the gh-releases-zsync URL.
#   One command produces BOTH deliverables:
#     release/Agent.Smith.Reloaded-<ver>.AppImage        (UPDATEINFO header embedded)
#     release/Agent.Smith.Reloaded-<ver>.AppImage.zsync  (delta file, auto-generated by appimagetool's bundled zsyncmake)
#
# Upload BOTH to the GitHub Release. The .deb is uploaded alongside as usual.
#
# Usage:
#   npm run dist && bash scripts/build-updatable-appimage.sh
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
RELEASE="$ROOT/release"
UNPACKED="$RELEASE/linux-unpacked"
CHROME="$ROOT/vendor/appdir-chrome"
AITOOL="$ROOT/vendor/appimagetool-x86_64.AppImage"

# --- update channel (must match the repo + asset naming convention) ---------
GH_OWNER="6Morpheus6"
GH_REPO="Agent_Smith-Reloaded"
UPDATE_URL="gh-releases-zsync|${GH_OWNER}|${GH_REPO}|latest|Agent.Smith.Reloaded-*.AppImage.zsync"

# --- sanity checks -----------------------------------------------------------
[ -d "$UNPACKED" ] || { echo "ERROR: $UNPACKED missing — run 'npm run dist' first." >&2; exit 1; }
[ -x "$AITOOL" ]   || { echo "ERROR: appimagetool not found at $AITOOL (vendor it into vendor/)." >&2; exit 1; }
[ -f "$CHROME/AppRun" ] || { echo "ERROR: chrome parts missing in $CHROME." >&2; exit 1; }

VERSION="$(node -p "require('$ROOT/package.json').version")"
PRODUCT_NAME="Agent Smith Reloaded"
DESCRIPTION="$(node -p "require('$ROOT/package.json').description")"
# Repo asset convention: Agent.Smith.Reloaded-<ver>.AppImage (dots, NOT the repo's underscore/hyphen)
OUT_BASENAME="Agent.Smith.Reloaded-${VERSION}"
OUT_APPIMAGE="$RELEASE/${OUT_BASENAME}.AppImage"
OUT_ZSYNC="${OUT_APPIMAGE}.zsync"

echo "==> Building updatable AppImage v${VERSION}"
echo "    update URL: ${UPDATE_URL}"

# --- assemble AppDir ---------------------------------------------------------
APPDIR="$(mktemp -d "$RELEASE/.appdir-build.XXXXXX")"
trap 'rm -rf "$APPDIR"' EXIT
mkdir -p "$APPDIR/AppDir"

cp -a "$UNPACKED/." "$APPDIR/AppDir/"
cp -a "$CHROME/AppRun" "$APPDIR/AppDir/AppRun"
chmod +x "$APPDIR/AppDir/AppRun"
cp -a "$CHROME/usr" "$APPDIR/AppDir/usr"
ln -sf usr/share/icons/hicolor/1024x1024/apps/agent-smith.png "$APPDIR/AppDir/.DirIcon"
ln -sf usr/share/icons/hicolor/1024x1024/apps/agent-smith.png "$APPDIR/AppDir/agent-smith.png"

# .desktop — same shape electron-builder emits (appimagetool requires Categories=)
cat > "$APPDIR/AppDir/agent-smith.desktop" <<EOF
[Desktop Entry]
Name=${PRODUCT_NAME}
Exec=AppRun --no-sandbox %U
Terminal=false
Type=Application
Icon=agent-smith
StartupWMClass=${PRODUCT_NAME}
X-AppImage-Version=${VERSION}
Comment=${DESCRIPTION}
Categories=Utility;
EOF

# --- build with update info (appimagetool auto-generates the .zsync) --------
rm -f "$RELEASE/${OUT_BASENAME}.AppImage" "$RELEASE/${OUT_BASENAME}.AppImage.zsync"
# appimagetool writes <basename>.zsync into its CWD, so run from release/ with a relative output name
( cd "$RELEASE" && ARCH=x86_64 "$AITOOL" -u "$UPDATE_URL" "$APPDIR/AppDir" "${OUT_BASENAME}.AppImage" )

# --- verify ------------------------------------------------------------------
echo "==> Verifying"
EMBEDDED="$("$OUT_APPIMAGE" --appimage-updateinfo 2>/dev/null || true)"
if [ "$EMBEDDED" != "$UPDATE_URL" ]; then
  echo "ERROR: UPDATEINFO mismatch." >&2
  echo "  expected: $UPDATE_URL" >&2
  echo "  embedded: ${EMBEDDED:-<none>}" >&2
  exit 1
fi
echo "    header OK: $EMBEDDED"

[ -f "$OUT_ZSYNC" ] || { echo "ERROR: .zsync file was not generated." >&2; exit 1; }
ZLEN="$(grep -a '^Length:' "$OUT_ZSYNC" | awk '{print $2}')"
ALEN="$(stat -c%s "$OUT_APPIMAGE")"
[ "$ZLEN" = "$ALEN" ] || { echo "ERROR: zsync Length ($ZLEN) != AppImage size ($ALEN)." >&2; exit 1; }
echo "    zsync OK : $OUT_ZSYNC (Length=$ALEN matches)"

# --- tidy: drop electron-builder's non-updatable duplicate -------------------
PLAIN="$RELEASE/${PRODUCT_NAME}-${VERSION}.AppImage"
if [ -f "$PLAIN" ]; then
  echo "==> Removing non-updatable duplicate: $(basename "$PLAIN")"
  rm -f "$PLAIN" "${PLAIN}.blockmap"
fi

echo ""
echo "DONE. Upload these to the GitHub Release (tag v${VERSION}):"
echo "    $OUT_APPIMAGE"
echo "    $OUT_ZSYNC"
echo "    $RELEASE/agent-smith_${VERSION}_amd64.deb"
