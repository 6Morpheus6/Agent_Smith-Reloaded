#!/usr/bin/env node
/**
 * gen-electron-assets-manifest — regenerate src/shared/electronAssetsManifest.js from vendor/.
 *
 * v55.3: the Electron Depot's ~635 MB of pre-provisioned runtimes/toolsets (vendor/) are no
 * longer SHIPPED inside the AppImage/.deb (they pushed the package past GitHub's free-tier
 * upload limit). Instead, on first launch the app auto-detects what is missing from the local
 * cache and downloads exactly that from these pinned URLs. This manifest is the single source
 * of truth for WHAT to fetch: exact URL + sizeBytes + sha256 per asset, so a download can be
 * integrity-verified before it is trusted.
 *
 * Run this whenever vendor/ changes (a new Electron runtime or builder toolset is added):
 *   node scripts/gen-electron-assets-manifest.js
 * It reads the REAL files on disk (size + sha256) and rewrites the manifest module. The URLs are
 * derived with the SAME pure helpers electronDepot uses, so they match what @electron/get /
 * app-builder-lib resolve at runtime.
 */
'use strict';

const crypto = require('crypto');
const fs = require('fs');
const path = require('path');

const { electronArtifactUrl } = require('../src/main/services/electronDepot.js');

const root = path.join(__dirname, '..');
const vendorDir = path.join(root, 'vendor');
const outPath = path.join(root, 'src', 'shared', 'electronAssetsManifest.js');

function sha256OfFile(file) {
    const h = crypto.createHash('sha256');
    h.update(fs.readFileSync(file));
    return h.digest('hex');
}

/** electron-builder-binaries release URL (mirrors app-builder-lib getBinariesMirrorUrl default). */
function builderToolsetUrl(releaseName, filenameWithExt) {
    return `https://github.com/electron-userland/electron-builder-binaries/releases/download/${releaseName}/${filenameWithExt}`;
}

const entries = [];

// 1) Electron runtime zips: vendor/electron/<platform>-<arch>/electron-vX.Y.Z-<platform>-<arch>.zip
const electronVendor = path.join(vendorDir, 'electron');
if (fs.existsSync(electronVendor)) {
    for (const platArch of fs.readdirSync(electronVendor).sort()) {
        const dir = path.join(electronVendor, platArch);
        if (!fs.statSync(dir).isDirectory()) continue;
        const mPlat = /^([a-z0-9]+)-([a-z0-9]+)$/.exec(platArch); // linux-x64 → [linux, x64]
        if (!mPlat) continue;
        const [, platformName, arch] = mPlat;
        for (const file of fs.readdirSync(dir).sort()) {
            const m = /^electron-v?(\d+\.\d+\.\d+)-([a-z0-9]+)-([a-z0-9]+)\.zip$/.exec(file);
            if (!m) continue;
            const [, version, pName, aName] = m;
            const full = path.join(dir, file);
            entries.push({
                kind: 'electron-runtime',
                name: file,
                version,
                platform: pName,
                arch: aName,
                releaseName: null,
                url: electronArtifactUrl(version, pName, aName),
                sizeBytes: fs.statSync(full).size,
                sha256: sha256OfFile(full)
            });
        }
    }
}

// 2) electron-builder toolsets: vendor/electron-builder/<releaseName>/<archive> (archives only —
//    the pre-extracted dirs + .state are derived by app-builder-lib on first use, not shipped).
const builderVendor = path.join(vendorDir, 'electron-builder');
if (fs.existsSync(builderVendor)) {
    for (const releaseName of fs.readdirSync(builderVendor).sort()) {
        const relSrc = path.join(builderVendor, releaseName);
        if (!fs.statSync(relSrc).isDirectory()) continue;
        for (const entry of fs.readdirSync(relSrc).sort()) {
            if (!/\.(7z|tar\.gz|tgz)$/.test(entry)) continue; // archives only
            const full = path.join(relSrc, entry);
            entries.push({
                kind: 'builder-toolset',
                name: entry,
                version: null,
                platform: null,
                arch: null,
                releaseName,
                url: builderToolsetUrl(releaseName, entry),
                sizeBytes: fs.statSync(full).size,
                sha256: sha256OfFile(full)
            });
        }
    }
}

if (!entries.length) {
    console.error('[gen-electron-assets-manifest] no assets found under vendor/ — nothing to write.');
    process.exit(1);
}

const totalBytes = entries.reduce((n, e) => n + e.sizeBytes, 0);
const fmt = (b) => `${(b / (1024 * 1024)).toFixed(1)} MB`;

let out = `/**
 * Electron Depot asset manifest — AUTO-GENERATED by scripts/gen-electron-assets-manifest.js.
 * DO NOT EDIT BY HAND: change vendor/ and re-run the generator instead.
 *
 * v55.3: these assets are no longer bundled in the AppImage/.deb (they pushed the package past
 * GitHub's free-tier upload limit). On first launch src/main/services/electronAssets.js detects
 * what is missing from the local cache and downloads exactly this set, verifying sha256 before
 * trusting each file. The destination paths are computed by electronAssets.js using the SAME pure
 * helpers as electronDepot.seedDepot(), so a downloaded asset lands byte-for-byte where
 * @electron/get / app-builder-lib already look (a seeded depot and a downloaded depot are
 * indistinguishable to the build tools).
 */
'use strict';

// ${entries.length} assets, ~${fmt(totalBytes)} total.
const ELECTRON_ASSETS_MANIFEST = [
`;
for (const e of entries) {
    out += `    {\n`;
    out += `        kind: '${e.kind}',\n`;
    out += `        name: ${JSON.stringify(e.name)},\n`;
    out += `        version: ${e.version ? JSON.stringify(e.version) : 'null'},\n`;
    out += `        platform: ${e.platform ? JSON.stringify(e.platform) : 'null'},\n`;
    out += `        arch: ${e.arch ? JSON.stringify(e.arch) : 'null'},\n`;
    out += `        releaseName: ${e.releaseName ? JSON.stringify(e.releaseName) : 'null'},\n`;
    out += `        url: ${JSON.stringify(e.url)},\n`;
    out += `        sizeBytes: ${e.sizeBytes},\n`;
    out += `        sha256: '${e.sha256}'\n`;
    out += `    },\n`;
}
out += `];

module.exports = { ELECTRON_ASSETS_MANIFEST };
`;

fs.writeFileSync(outPath, out);
console.log(`[gen-electron-assets-manifest] wrote ${path.relative(root, outPath)} — ${entries.length} assets, ~${fmt(totalBytes)} total.`);
for (const e of entries) console.log(`  - [${e.kind}] ${e.name} (${fmt(e.sizeBytes)})`);
