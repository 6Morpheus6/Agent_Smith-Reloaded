/**
 * v53 — web_search display + post-search silence fixes.
 *
 * The reported bug: "web search fails to display results and takes a long time".
 * Reproduced live against LM Studio (qwen3-27b): after the web_search tool result
 * landed, the model's NEXT turn either chained into fetch_url (~50s of prompt
 * processing per hop) or returned an EMPTY stream (whole reply spent on internal
 * reasoning). The app then nudged ("Please summarize…") and looped — forever.
 * Meanwhile the only thing painted was a "sources" card that listed TITLES ONLY,
 * so to the user it read as: search ran, nothing displayed, no summary ever.
 *
 * Fixes under test:
 *   1. agentTools web_search returns COMPACT result text (snippets capped at 200
 *      chars) and a nudge that tells the model to answer NOW — not chain fetch_url.
 *   2. displayWebSearchResults renders each source with its LINKED title, URL and
 *      snippet (not titles only), for both the new compact shape and the legacy one.
 *   3. The chat loop's silent-turn nudge is BOUNDED: after 3 consecutive empty
 *      replies it ends the run with an honest note instead of spinning forever.
 *   4. Code Mode timeline shows the actual retrieved content for web_search /
 *      fetch_url (not a KV dump) and counts sources in the row summary.
 */
