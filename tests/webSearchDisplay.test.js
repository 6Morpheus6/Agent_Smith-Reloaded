// ── 3. chat loop: silent-turn nudge is bounded (no infinite "working…" spin) ───

test('silentTurns counter exists and bounds the post-tool silence loop', () => {
    // Declared before the while loop…
    const declIdx = APP_SRC.indexOf('let silentTurns = 0');
    assert.notEqual(declIdx, -1, 'silentTurns must be declared (let) in sendMessage');
    assert.ok(APP_SRC.indexOf('while (!finished)') > declIdx);

    // …incremented on a silent turn…
    const silentBranch = APP_SRC.slice(APP_SRC.indexOf('// BUG FIX: If model is silent after tool results'));
    assert.match(silentBranch, /silentTurns\+\+/);
    // …bounded at 3 with an honest end-of-run note (finished = true)…
    assert.match(silentBranch, /silentTurns >= 3/);
    const giveUpIdx = silentBranch.indexOf('silentTurns >= 3');
    // Window is generous on purpose: v53.5 inserted the web-search fallback block between the
    // counter and the give-up branch, so a tight window would fail on unrelated insertions.
    assert.ok(giveUpIdx > -1 && silentBranch.slice(giveUpIdx, giveUpIdx + 2600).includes('finished = true'), 'must END the run after 3 silent turns');
    // …and reset when a real reply lands.
    assert.match(APP_SRC, /else if \(turnCount > 1\) \{\s*silentTurns = 0/);
});

test('a streamed (non-empty) reply resets the silence counter', () => {
    const emitIdx = APP_SRC.indexOf('const emitStream');
    assert.notEqual(emitIdx, -1);
    assert.match(APP_SRC.slice(emitIdx, emitIdx + 260), /silentTurns = 0/);
});

