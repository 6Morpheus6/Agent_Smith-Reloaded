// ── 2. displayWebSearchResults: real content, not titles only ─────────────────

const APP_SRC = fs.readFileSync(path.join(__dirname, '..', 'src', 'renderer', 'app.js'), 'utf8');

/** Extract a top-level `function NAME(...) {...}` from app.js (ends at first column-0 `}`). */
function extractFunction(src, name) {
    const start = src.indexOf(`function ${name}(`);
    assert.notEqual(start, -1, `${name} must exist in app.js`);
    const endMarker = '\n}\n';
    const end = src.indexOf(endMarker, start);
    assert.notEqual(end, -1, `end of ${name}`);
    return src.slice(start, end + 2); // include the closing "}"
}

function makeDisplayFn(dom) {
    const messagesDiv = dom.window.document.createElement('div');
    dom.window.document.body.appendChild(messagesDiv);
    let scrolled = false;
    const factory = new dom.window.Function(
        'messagesContainer', 'scrollMessagesToLatest',
        extractFunction(APP_SRC, 'displayWebSearchResults') + '\nreturn displayWebSearchResults;'
    );
    return { fn: factory(messagesDiv, () => { scrolled = true; }), messagesDiv, wasScrolled: () => scrolled };
}

test('displayWebSearchResults renders linked titles + snippets (compact format)', () => {
    if (!JSDOM) return; // jsdom optional
    const dom = new JSDOM('<!doctype html><body></body>');
    global.window = dom.window; global.document = dom.window.document;
    const { fn, messagesDiv } = makeDisplayFn(dom);

    const text = [
        '1. First Source — the first snippet here',
        '   URL: https://a.test/page',
        '2. Second <Source> & "Friends" — second snippet',
        '   URL: https://b.test/'
    ].join('\n') + '\n\n[SYSTEM NUDGE]: The web search completed successfully…';

    fn('my query', text);
    const html = messagesDiv.innerHTML;
    assert.ok(html.includes('<a href="https://a.test/page"'), 'source 1 must be a real link');
    assert.ok(html.includes('<a href="https://b.test/"'), 'source 2 must be a real link');
    assert.ok(html.includes('the first snippet here'), 'snippet content must be visible (not just titles)');
    assert.ok(html.includes('second snippet'));
    // The nudge text itself must never leak into the card.
    assert.ok(!html.includes('[SYSTEM NUDGE]'));
});

